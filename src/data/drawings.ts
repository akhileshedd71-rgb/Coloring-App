// Original, hand-drawn vector pages. Every closed shape is a separate paint region.
type Shape = [
  path: string,
  colorNumber: number,
  labelX: number,
  labelY: number,
];
const oval = (x: number, y: number, rx: number, ry = rx) =>
  `M ${x - rx} ${y} a ${rx} ${ry} 0 1 0 ${rx * 2} 0 a ${rx} ${ry} 0 1 0 ${-rx * 2} 0 Z`;
const poly = (...points: number[]) =>
  `M ${points[0]} ${points[1]} ${points.slice(2).reduce((s, n, i) => s + (i % 2 ? ` ${n}` : ` L ${n}`), "")} Z`;
const star = (x: number, y: number, size: number) =>
  poly(
    ...Array.from({ length: 10 }, (_, i) => {
      const a = -Math.PI / 2 + (i * Math.PI) / 5;
      const r = i % 2 ? size * 0.46 : size;
      return [Math.round(x + Math.cos(a) * r), Math.round(y + Math.sin(a) * r)];
    }).flat(),
  );
const heart = (x: number, y: number, size: number) =>
  `M ${x} ${y + size * 0.65} C ${x - size * 1.6} ${y - size * 0.25} ${x - size * 0.75} ${y - size * 1.4} ${x} ${y - size * 0.6} C ${x + size * 0.75} ${y - size * 1.4} ${x + size * 1.6} ${y - size * 0.25} ${x} ${y + size * 0.65} Z`;
const cloud = (x: number, y: number, s: number) =>
  `M ${x - s} ${y + s * 0.3} C ${x - s * 1.5} ${y + s * 0.2} ${x - s * 1.3} ${y - s * 0.65} ${x - s * 0.65} ${y - s * 0.5} C ${x - s * 0.6} ${y - s * 1.3} ${x + s * 0.5} ${y - s * 1.3} ${x + s * 0.6} ${y - s * 0.5} C ${x + s * 1.4} ${y - s * 0.6} ${x + s * 1.55} ${y + s * 0.4} ${x + s} ${y + s * 0.4} Z`;
const eyes = (x: number, y: number, spacing: number) => [
  `M ${x - spacing} ${y} v 8`,
  `M ${x + spacing} ${y} v 8`,
];
const smile = (x: number, y: number, width = 28) =>
  `M ${x - width} ${y} Q ${x} ${y + width} ${x + width} ${y}`;
function page(
  id: string,
  title: string,
  category: string,
  accent: string,
  shapes: Shape[],
  lines: string[] = [],
  difficulty: Drawing["difficulty"] = "easy",
): Drawing {
  return {
    id,
    title,
    category,
    difficulty,
    accent,
    background: "#FFFFFF",
    regions: shapes.map(
      ([d, number, x, y], i): Region => ({
        id: `${id}-${i}`,
        d,
        number,
        color: PALETTE[number - 1],
        label: [x, y],
      }),
    ),
    lines,
  };
}

